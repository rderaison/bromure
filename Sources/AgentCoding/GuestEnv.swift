import Foundation

// api_key.env, the guest's credential environment: shared by the macOS
// session disk and the Linux daemon (each writes the file into its meta
// share; the guest's .bashrc sources it).

extension SessionDisk {
    // api_key.env — sourced by .bashrc inside the guest. Exports
    // the env var for every enabled tool in token mode. The values
    // are FAKE tokens minted by SessionTokenPlan: the host's MITM
    // engine swaps each fake for the real key on the wire. The VM
    // only ever holds the fake, so the worst case of a guest leak
    // is a useless string.
    static func apiKeyEnvLines(profile: Profile, tokenPlan: SessionTokenPlan?,
                               registrationMode: Bool) -> [String] {
        var lines: [String] = ["# Generated by Bromure AC; do not edit."]
        var exported: Set<String> = []
        for spec in profile.allToolSpecs {
            guard spec.authMode == .token, let real = spec.apiKey, !real.isEmpty else { continue }
            let value: String
            switch spec.tool {
            case .claude:
                // Through a gateway (OpenRouter): ANTHROPIC_BASE_URL, the
                // stand-in key as a bearer (swapped on the gateway's host), an
                // explicitly EMPTY ANTHROPIC_API_KEY so the two never conflict,
                // and the gateway's model ids pinned per tier.
                if let base = profile.claudeGatewayBaseURL, let host = URL(string: base)?.host {
                    let fake = tokenPlan?.fakeForCloud(host: host) ?? real
                    lines.append("export ANTHROPIC_BASE_URL=\(shellQuote(base))")
                    lines.append("export ANTHROPIC_AUTH_TOKEN=\(shellQuote(fake))")
                    lines.append("export ANTHROPIC_API_KEY=''")
                    exported.insert("ANTHROPIC_API_KEY")
                    let m = profile.claudeGatewayModels
                    if let main = m["medium"] ?? m["large"] ?? m["small"] {
                        let small = m["small"] ?? main
                        lines.append("export ANTHROPIC_MODEL=\(shellQuote(main))")
                        lines.append("export ANTHROPIC_DEFAULT_SONNET_MODEL=\(shellQuote(m["medium"] ?? main))")
                        lines.append("export ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellQuote(m["large"] ?? main))")
                        lines.append("export ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellQuote(small))")
                        lines.append("export ANTHROPIC_SMALL_FAST_MODEL=\(shellQuote(small))")
                    }
                    continue
                }
                value = tokenPlan?.fakeForAnthropic() ?? real
            case .codex:
                value = tokenPlan?.fakeForOpenAI() ?? real
            case .grok:
                value = tokenPlan?.fakeForXAI() ?? real
            case .kimi:
                value = tokenPlan?.fakeForKimi() ?? real
            case .omp:
                value = tokenPlan?.fakeForOmp() ?? real
            }
            // omp is provider-agnostic: write the SELECTED provider's env var
            // (ANTHROPIC_API_KEY by default, OPENAI_API_KEY/XAI_API_KEY/… when
            // switched), not the tool's default.
            let envVar = spec.tool == .omp
                ? spec.effectiveOmpProvider.apiKeyEnvVar
                : spec.tool.apiKeyEnvVar
            lines.append("export \(envVar)=\(shellQuote(value))")
            exported.insert(envVar)
        }
        // omp's other providers (Settings → Models): their keys, never over
        // a variable another agent already set (a local Codex's OPENAI_API_KEY
        // is the engine's key, not OpenAI's). A keyless custom server still
        // needs a value for omp's `apiKey:`.
        // Claude's subscription placeholder takes ANTHROPIC_API_KEY below.
        if tokenPlan?.claudeSubscriptionBogusKey != nil, profile.claudeGatewayBaseURL == nil,
           tokenPlan?.claudeOAuthStandIn == nil {
            exported.insert("ANTHROPIC_API_KEY")
        }
        for extra in profile.ompExtraProviders where !exported.contains(extra.envVar) {
            let value = extra.apiKey.isEmpty
                ? "none"
                : (extra.host.flatMap { tokenPlan?.fakeForCloud(host: $0) } ?? extra.apiKey)
            lines.append("export \(extra.envVar)=\(shellQuote(value))")
            exported.insert(extra.envVar)
        }
        // Claude subscription mode: export the bogus ANTHROPIC_API_KEY so Claude
        // Code runs in API-key mode (never doing OAuth in the guest). The proxy
        // swaps it for a live subscription OAuth Bearer token held on the host.
        // Only present when a subscription credential is registered (see
        // makeTokenPlan); otherwise the guest logs in interactively as before.
        // With account features on, Claude signs in with the OAuth stand-in
        // (`~/.claude/.credentials.json`) instead — and an ANTHROPIC_API_KEY
        // in the environment would win over it.
        if let bogus = tokenPlan?.claudeSubscriptionBogusKey, profile.claudeGatewayBaseURL == nil,
           tokenPlan?.claudeOAuthStandIn == nil {
            lines.append("export ANTHROPIC_API_KEY=\(shellQuote(bogus))")
        }
        // Claude on Anthropic itself (API key or subscription): the model(s)
        // chosen in Preferences → Models. Only what was picked is pinned —
        // nothing picked = Claude Code's own default, and an in-session
        // /model still wins.
        if profile.claudeGatewayBaseURL == nil, !profile.bedrockEnabled,
           profile.allToolSpecs.contains(where: {
               $0.tool == .claude && ($0.authMode == .token || $0.authMode == .subscription)
           }) {
            let m = profile.claudeGatewayModels
            if let main = m["medium"] {
                lines.append("export ANTHROPIC_MODEL=\(shellQuote(main))")
            }
            if let large = m["large"] {
                lines.append("export ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellQuote(large))")
            }
            if let small = m["small"] {
                lines.append("export ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellQuote(small))")
                lines.append("export ANTHROPIC_SMALL_FAST_MODEL=\(shellQuote(small))")
            }
        }
        // Manual tokens defined in the editor's Advanced section.
        // Same trick as above: we inject the fake; the host swaps it
        // for the real value at the proxy.
        if let plan = tokenPlan {
            for (envName, fake) in plan.manualEnvExports {
                lines.append("export \(envName)=\(shellQuote(fake))")
            }
            // HTTPS-database secrets: inject the fake under the user-named
            // env var(s); the host swaps it to the real value on the wire.
            for (envName, fake) in plan.httpDatabaseEnvExports {
                lines.append("export \(envName)=\(shellQuote(fake))")
            }
            // MCP bearer tokens — Claude Code reads bearerTokenEnvVar
            // from the system environment for HTTP servers, not from
            // the config's env block.
            for entry in plan.mcpBearerFakes where !entry.envVarName.isEmpty {
                lines.append("export \(entry.envVarName)=\(shellQuote(entry.fake))")
            }
        }

        lines.append("export BROMURE_AC_TOOL=\(profile.tool.rawValue)")
        lines.append("export BROMURE_AC_AUTH=\(profile.authMode.rawValue)")
        if registrationMode { lines.append("export BROMURE_AC_REGISTER=1") }
        return lines
    }
}

private func shellQuote(_ s: String) -> String {
    "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
}
