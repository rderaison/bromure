import Foundation

// api_key.env, the guest's credential environment: shared by the macOS
// session disk and the Linux daemon (each writes the file into its meta
// share; the guest's .bashrc sources it).

extension SessionDisk {
    // api_key.env — sourced by .bashrc inside the guest. Exports
    // the env var for every enabled tool in token mode. The values
    // are FAKE tokens minted by SessionTokenPlan: the host's MITM
    // engine swaps each fake for the real key on the wire. The VM
    // only ever holds the fake, so the worst case of a guest leak
    // is a useless string.
    static func apiKeyEnvLines(profile: Profile, tokenPlan: SessionTokenPlan?,
                               registrationMode: Bool) -> [String] {
        var lines: [String] = ["# Generated by Bromure AC; do not edit."]
        var exported: Set<String> = []
        for spec in profile.allToolSpecs {
            guard spec.authMode == .token, let real = spec.apiKey, !real.isEmpty else { continue }
            let value: String
            switch spec.tool {
            case .claude:
                // Through a gateway (OpenRouter): ANTHROPIC_BASE_URL, the
                // stand-in key as a bearer (swapped on the gateway's host), an
                // explicitly EMPTY ANTHROPIC_API_KEY so the two never conflict,
                // and the gateway's model ids pinned per tier.
                if let base = profile.claudeGatewayBaseURL, let host = URL(string: base)?.host {
                    let fake = tokenPlan?.fakeForCloud(host: host) ?? real
                    lines.append("export ANTHROPIC_BASE_URL=\(shellQuote(base))")
                    lines.append("export ANTHROPIC_AUTH_TOKEN=\(shellQuote(fake))")
                    lines.append("export ANTHROPIC_API_KEY=''")
                    exported.insert("ANTHROPIC_API_KEY")
                    let m = profile.claudeGatewayModels
                    if let main = m["medium"] ?? m["large"] ?? m["small"] {
                        let small = m["small"] ?? main
                        lines.append("export ANTHROPIC_MODEL=\(shellQuote(main))")
                        lines.append("export ANTHROPIC_DEFAULT_SONNET_MODEL=\(shellQuote(m["medium"] ?? main))")
                        lines.append("export ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellQuote(m["large"] ?? main))")
                        lines.append("export ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellQuote(small))")
                        lines.append("export ANTHROPIC_SMALL_FAST_MODEL=\(shellQuote(small))")
                    }
                    continue
                }
                value = tokenPlan?.fakeForAnthropic() ?? real
            case .codex:
                value = tokenPlan?.fakeForOpenAI() ?? real
            case .grok:
                value = tokenPlan?.fakeForXAI() ?? real
            case .kimi:
                value = tokenPlan?.fakeForKimi() ?? real
            case .omp:
                value = tokenPlan?.fakeForOmp() ?? real
            }
            // omp is provider-agnostic: write the SELECTED provider's env var
            // (ANTHROPIC_API_KEY by default, OPENAI_API_KEY/XAI_API_KEY/… when
            // switched), not the tool's default.
            let envVar = spec.tool == .omp
                ? spec.effectiveOmpProvider.apiKeyEnvVar
                : spec.tool.apiKeyEnvVar
            lines.append("export \(envVar)=\(shellQuote(value))")
            exported.insert(envVar)
        }
        // omp's other providers (Settings → Models): their keys, never over
        // a variable another agent already set (a local Codex's OPENAI_API_KEY
        // is the engine's key, not OpenAI's). A keyless custom server still
        // needs a value for omp's `apiKey:`.
        // Claude's subscription placeholder takes ANTHROPIC_API_KEY below.
        if tokenPlan?.claudeSubscriptionBogusKey != nil, profile.claudeGatewayBaseURL == nil,
           tokenPlan?.claudeOAuthStandIn == nil {
            exported.insert("ANTHROPIC_API_KEY")
        }
        // A key with no stand-in (its base URL names no host the proxy can
        // swap on, e.g. "10.0.0.5:8000/v1" with no scheme) never goes in as
        // itself: the VM gets "none", as for a keyless server.
        for extra in profile.ompExtraProviders where !exported.contains(extra.envVar) {
            let value = extra.apiKey.isEmpty
                ? "none"
                : (extra.host.flatMap { tokenPlan?.fakeForCloud(host: $0) } ?? "none")
            lines.append("export \(extra.envVar)=\(shellQuote(value))")
            exported.insert(extra.envVar)
        }
        // Claude subscription mode: export the bogus ANTHROPIC_API_KEY so Claude
        // Code runs in API-key mode (never doing OAuth in the guest). The proxy
        // swaps it for a live subscription OAuth Bearer token held on the host.
        // Only present when a subscription credential is registered (see
        // makeTokenPlan); otherwise the guest logs in interactively as before.
        // With account features on, Claude signs in with the OAuth stand-in
        // (`~/.claude/.credentials.json`) instead — and an ANTHROPIC_API_KEY
        // in the environment would win over it.
        if let bogus = tokenPlan?.claudeSubscriptionBogusKey, profile.claudeGatewayBaseURL == nil,
           tokenPlan?.claudeOAuthStandIn == nil {
            lines.append("export ANTHROPIC_API_KEY=\(shellQuote(bogus))")
        }
        // Claude on Anthropic itself (API key or subscription): the model(s)
        // chosen in Preferences → Models. Only what was picked is pinned —
        // nothing picked = Claude Code's own default, and an in-session
        // /model still wins.
        if profile.claudeGatewayBaseURL == nil, !profile.bedrockEnabled,
           profile.allToolSpecs.contains(where: {
               $0.tool == .claude && ($0.authMode == .token || $0.authMode == .subscription)
           }) {
            let m = profile.claudeGatewayModels
            if let main = m["medium"] {
                lines.append("export ANTHROPIC_MODEL=\(shellQuote(main))")
            }
            if let large = m["large"] {
                lines.append("export ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellQuote(large))")
            }
            if let small = m["small"] {
                lines.append("export ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellQuote(small))")
                lines.append("export ANTHROPIC_SMALL_FAST_MODEL=\(shellQuote(small))")
            }
        }
        // Manual tokens defined in the editor's Advanced section.
        // Same trick as above: we inject the fake; the host swaps it
        // for the real value at the proxy.
        if let plan = tokenPlan {
            for (envName, fake) in plan.manualEnvExports {
                lines.append("export \(envName)=\(shellQuote(fake))")
            }
            // HTTPS-database secrets: inject the fake under the user-named
            // env var(s); the host swaps it to the real value on the wire.
            for (envName, fake) in plan.httpDatabaseEnvExports {
                lines.append("export \(envName)=\(shellQuote(fake))")
            }
            // MCP bearer tokens — Claude Code reads bearerTokenEnvVar
            // from the system environment for HTTP servers, not from
            // the config's env block.
            for entry in plan.mcpBearerFakes where !entry.envVarName.isEmpty {
                lines.append("export \(entry.envVarName)=\(shellQuote(entry.fake))")
            }
        }

        lines.append("export BROMURE_AC_TOOL=\(profile.tool.rawValue)")
        lines.append("export BROMURE_AC_AUTH=\(profile.authMode.rawValue)")
        if registrationMode { lines.append("export BROMURE_AC_REGISTER=1") }
        return lines
    }

    /// proxy.env's lines (sourced by .bashrc for every shell): the
    /// cooperative proxy and CA hints, the forge and service tokens' fakes
    /// (gh/glab, DigitalOcean, Linear, Twilio), the AWS region, local-model
    /// agents, Kimi's region and the user's own variables. macOS's session
    /// disk and the Linux daemon both write the file from these.
    /// `cooperativeAlways`: the proxy variables are set whatever the
    /// workspace (a host with no transparent interception: Linux's).
    static func proxyEnvLines(profile: Profile, tokenPlan: SessionTokenPlan?, proxyPort: Int,
                              extraNoProxy: [String], extraInsecureRegistries: [String],
                              cooperativeAlways: Bool = false) -> [String] {
        var ghEnv: [String] = []
        if let plan = tokenPlan {
            for cred in profile.gitHTTPSCredentials where cred.isUsable {
                guard let fake = plan.fakeForGitHTTPS(host: cred.host,
                                                      username: cred.effectiveUsername) else {
                    continue
                }
                let h = cred.host.lowercased()
                if h == "github.com" || h.hasSuffix(".github.com") {
                    ghEnv.append("export GH_TOKEN=\(shellQuote(fake))")
                    ghEnv.append("export GITHUB_TOKEN=\(shellQuote(fake))")
                } else if h == "gitlab.com" || h.hasPrefix("gitlab.") {
                    ghEnv.append("export GITLAB_TOKEN=\(shellQuote(fake))")
                    ghEnv.append("export GLAB_TOKEN=\(shellQuote(fake))")
                }
            }
            // DigitalOcean: doctl + most terraform / SDK clients
            // honour DIGITALOCEAN_ACCESS_TOKEN — env beats the
            // ~/.config/doctl/config.yaml path.
            if let doFake = plan.fakeForDigitalOcean() {
                ghEnv.append("export DIGITALOCEAN_ACCESS_TOKEN=\(shellQuote(doFake))")
            }
            // Linear: the SDK, MCP servers and CLI tools all read
            // LINEAR_API_KEY. No config file to write — env only.
            if let linFake = plan.fakeForLinear() {
                ghEnv.append("export LINEAR_API_KEY=\(shellQuote(linFake))")
            }
            // Twilio: the Twilio helper libraries + CLI read
            // TWILIO_ACCOUNT_SID + TWILIO_AUTH_TOKEN. The SID is identity
            // (not a secret) so it's exported verbatim; the token is the
            // FAKE — the proxy swaps the Basic blob to the real secret on
            // api.twilio.com.
            if let twFake = plan.fakeForTwilio() {
                let sid = profile.twilioCredential.sid
                    .trimmingCharacters(in: .whitespacesAndNewlines)
                if !sid.isEmpty {
                    ghEnv.append("export TWILIO_ACCOUNT_SID=\(shellQuote(sid))")
                }
                ghEnv.append("export TWILIO_AUTH_TOKEN=\(shellQuote(twFake))")
            }
        }
        // AWS: secret stays on host. The SDK pulls credentials on
        // demand via the `credential_process` line in ~/.aws/config,
        // which shells out to /mnt/bromure-meta/bromure-aws-creds.py.
        // We must NOT export AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY
        // / AWS_SESSION_TOKEN here: env vars beat credential_process
        // in the SDK's chain, and they'd also defeat the
        // no-secret-on-disk guarantee (envs leak via /proc, ps -E,
        // and shell history). Region is fine — it's not a secret.
        let aws = profile.awsCredentials
        if aws.isUsable {
            let region = aws.region.trimmingCharacters(in: .whitespaces)
            if !region.isEmpty {
                ghEnv.append("export AWS_DEFAULT_REGION=\(shellQuote(region))")
                ghEnv.append("export AWS_REGION=\(shellQuote(region))")
            }
        }

        var proxyLines: [String] = [
            "# Generated by Bromure AC; do not edit.",
        ]
        // Point proxy-aware tools at the host MITM. ALWAYS set — even when
        // `disableTransparentProxy` is on. That flag governs only the
        // TRANSPARENT (IP-stack) divert at the switch: with it on, traffic
        // that ignores the proxy env (raw sockets, cert-pinned clients)
        // reaches the real network directly, but the COOPERATIVE proxy stays
        // live so apt/git/pip/curl/node — and the agent's own API calls with
        // their credential/token swap — still go through Bromure and get
        // tracing + guardrails. (Previously this dropped the env too, which
        // made "disable transparent interception" silently kill the proxy +
        // token swap entirely.)
        // Two exceptions, where everything goes through transparent
        // interception and the workload sees no proxy variables at all
        // (NO_PROXY included — it means nothing without the others):
        // - the strict sandbox: a connection through the local proxy
        //   bridge can't be attributed to the executable behind it;
        // - an OpenShell policy with transparent interception on: OpenShell
        //   sandboxes have no proxy environment (its no_proxy e2e test
        //   asserts it), and the transparent path enforces the same rules.
        let cooperativeProxy = cooperativeAlways || (!profile.effectiveStrictSandbox
            && !(profile.usesOpenShellPolicy && !profile.effectiveDisableTransparentProxy))
        if cooperativeProxy {
            let noProxy = (["localhost", "127.0.0.1", "::1"] + extraNoProxy).joined(separator: ",")
            proxyLines += [
                "export http_proxy=http://127.0.0.1:\(proxyPort)",
                "export https_proxy=http://127.0.0.1:\(proxyPort)",
                "export HTTP_PROXY=http://127.0.0.1:\(proxyPort)",
                "export HTTPS_PROXY=http://127.0.0.1:\(proxyPort)",
                "export NO_PROXY=\(noProxy)",
                "export no_proxy=\(noProxy)",
            ]
        }
        proxyLines += [
            "export NODE_EXTRA_CA_CERTS=/etc/ssl/certs/bromure-ca.pem",
            "export REQUESTS_CA_BUNDLE=/etc/ssl/certs/ca-certificates.crt",
            "export SSL_CERT_FILE=/etc/ssl/certs/ca-certificates.crt",
            "export CARGO_HTTP_CAINFO=/etc/ssl/certs/ca-certificates.crt",
            "export GIT_SSL_CAINFO=/etc/ssl/certs/ca-certificates.crt",
            // pip vendors its own certifi and ignores SSL_CERT_FILE /
            // REQUESTS_CA_BUNDLE — PIP_CERT is the only env knob it reads.
            "export PIP_CERT=/etc/ssl/certs/ca-certificates.crt",
            // curl links the system bundle already, but a statically
            // built curl (or one in a stripped env) honors this instead.
            "export CURL_CA_BUNDLE=/etc/ssl/certs/ca-certificates.crt",
            // Deno + AWS CLI each ignore SSL_CERT_FILE and read their own.
            "export DENO_CERT=/etc/ssl/certs/ca-certificates.crt",
            "export AWS_CA_BUNDLE=/etc/ssl/certs/ca-certificates.crt",
            // gcloud bundles its own certifi — this is the only knob it reads.
            "export CLOUDSDK_CORE_CUSTOM_CA_CERTS_FILE=/etc/ssl/certs/ca-certificates.crt",
            // gRPC clients (some Google SDKs, buf, etc.) read their own roots.
            "export GRPC_DEFAULT_SSL_ROOTS_FILE_PATH=/etc/ssl/certs/ca-certificates.crt",
            // OpenSSL dir-based lookups (belt-and-suspenders alongside SSL_CERT_FILE).
            "export SSL_CERT_DIR=/etc/ssl/certs",
            // No private key in the VM — use the host-bridged agent.
            "export SSH_AUTH_SOCK=/tmp/bromure-agent.sock",
        ]
        proxyLines.append(contentsOf: ghEnv)
        if let first = extraInsecureRegistries.first {
            proxyLines.append("export BROMURE_REGISTRY=\(shellQuote(first))")
        }

        // Local inference (Path 1, vLLM.md §3.3). For each tool the user
        // set to "Local model", pin it at the on-host engine via the
        // vsock bridge (127.0.0.1:11434 → vsock 8446 → loopback engine)
        // and point every model slot at the selected model. 127.0.0.1 is
        // already in NO_PROXY above, so these bypass the MITM proxy and
        // hit the bridge directly. The auth token is this profile's
        // persistent per-VM engine key — it authenticates the call and
        // identifies the VM to the engine (for per-VM tracing), and is
        // stable across reboots/suspend-reset so a resumed VM's baked key
        // still validates after the app relaunches.
        // (This is the explicit per-tool path; transparent Hybrid routing
        // is handled separately by the MITM engine, not here.)
        // Every "Local model" agent serves the profile's single active
        // model (chosen in Local Models) — agents no longer pick their own.
        if let localModel = profile.localAgentModelName {
            // Agents get the REAL model name (the repo the engine serves /
            // the custom server's id), not the old `bromure-local`
            // sentinel: agents key capability lookups, context sizing, and
            // their UI off the name, so opacity here made them misbehave.
            // Switching the model live still works — the refresh restages
            // these files, and the repair proxy remaps the RETIRED name
            // for the still-running agent (its env is frozen at exec).
            let key = EngineKey.perVM(profileID: profile.id)
            for spec in profile.allToolSpecs where spec.authMode == .local {
                for export in spec.tool.localEnvExports(model: localModel, key: key) {
                    proxyLines.append("export \(export.name)=\(shellQuote(export.value))")
                }
            }
        }

        // Kimi Code region — force the international `global` endpoints for
        // a Kimi subscription (see `kimiRegionEnvExports`).
        proxyLines.append(contentsOf: Self.kimiRegionEnvExports(for: profile))

        // User-defined env vars from the profile. No substitution
        // — values land in the VM verbatim. Names are filtered to
        // POSIX shape at the boundary so an invalid character in
        // the editor can't produce an unsourceable shell line.
        for env in profile.environmentVariables where env.isUsable {
            let name = env.name.trimmingCharacters(in: .whitespaces)
            proxyLines.append("export \(name)=\(shellQuote(env.value))")
        }
        return proxyLines
    }

    /// The guest env exports that pin a Kimi **subscription** to the CLI's
    /// international (`global`) region — empty for any other configuration.
    ///
    /// The `@moonshot-ai/kimi-code` CLI defaults to the mainland-China region
    /// (`auth.kimi.com` / `api.kimi.com`), which rejects a non-China account.
    /// `KIMI_CODE_OAUTH_HOST` / `KIMI_CODE_BASE_URL` are its own authoritative
    /// region override (verified live), so setting them makes `kimi login`'s
    /// device flow hit `auth.kimi.ai` (in the registration VM) and the managed
    /// API calls hit `api.kimi.ai/coding` (in every session). Token (moonshot
    /// API-key) mode is left alone — it already uses the international
    /// `api.moonshot.ai`. The host side (refresh + proxy swap) follows the same
    /// hosts via ``KimiRegion``. Pure so it's unit-tested (see KimiAgentTests).
    static func kimiRegionEnvExports(for profile: Profile) -> [String] {
        guard profile.allToolSpecs.contains(where: { $0.tool == .kimi && $0.authMode == .subscription })
        else { return [] }
        return [
            "export KIMI_CODE_OAUTH_HOST=https://\(KimiRegion.oauthHost)",
            "export KIMI_CODE_BASE_URL=\(KimiRegion.baseURL)",
        ]
    }
}

private func shellQuote(_ s: String) -> String {
    "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
}
