#!/usr/bin/env python3
"""Generates Sources/ACLinux/HomeSeedContent.generated.swift from macOS's
Sources/AgentCoding/Profile.swift: the profile-independent managed dotfiles of
the home seed (ProfileStore.populateManagedHome). The string literals are copied
as SOURCE TEXT, delimiters and indentation included, so Swift reads them exactly
as it reads the originals. The unit test HomeSeedTests regenerates and compares:
a change on the macOS side fails CI until this is re-run.

  linux/ACLinux/scripts/gen-home-seed.py [--check]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(PKG))
SRC = os.path.join(REPO, "Sources", "AgentCoding", "Profile.swift")
OUT = os.path.join(PKG, "Sources", "ACLinux", "HomeSeedContent.generated.swift")
STATIC = ["bashrcContent", "bashrcLocalSeed", "bashProfileContent", "profileContent", "agentCLIPackages"]


def static_let(src, name):
    """`static let <name> = <literal>` up to the end of the literal, verbatim."""
    m = re.search(r"^([ \t]*)(?:private )?static let %s = " % name, src, re.M)
    if not m:
        sys.exit("gen-home-seed: no `static let %s` in Profile.swift" % name)
    rest = src[m.end():]
    if rest.startswith('#"""'):
        end = rest.index('"""#', 4) + 4
    elif rest.startswith('"""'):
        end = rest.index('"""', 3) + 3
    elif rest.startswith("["):
        end = rest.index("]") + 1
    else:
        sys.exit("gen-home-seed: unexpected literal for %s" % name)
    return rest[:end]


def tmux_conf(src):
    """The inline triple-quoted literal written to ~/.tmux.conf."""
    m = re.search(r'try ("""\n.*?\n[ \t]*""")\.write\(to: home\.appendingPathComponent\("\.tmux\.conf"\)', src, re.S)
    if not m:
        sys.exit("gen-home-seed: the .tmux.conf literal moved")
    return m.group(1)


def generate():
    src = open(SRC).read()
    out = ["// GENERATED by linux/ACLinux/scripts/gen-home-seed.py from Sources/AgentCoding/Profile.swift.",
           "// Do not edit: re-run the script (HomeSeedTests fails when this is stale).",
           "// swiftlint:disable all", "",
           "/// The profile-independent managed dotfiles of the home seed, verbatim from",
           "/// ProfileStore (macOS). Stand-in until ACCore carries them.",
           "// @port-skip linux-only: generated copy of ProfileStore's seed constants",
           "enum HomeSeedContent {"]
    for name in STATIC:
        out.append("    // @port-skip linux-only: generated (ProfileStore.%s)" % name)
        out.append("    static let %s = %s" % (name, static_let(src, name)))
        out.append("")
    out.append("    // @port-skip linux-only: generated (the .tmux.conf literal in ProfileStore.populateManagedHome)")
    out.append("    static let tmuxConf = " + tmux_conf(src))
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT)
