import Foundation

extension Daemon {
    /// The guest's share of the intercepting proxy, in the meta share as
    /// macOS's SessionDisk.prepareMetadataShare writes it: the CA agentd
    /// installs (`bromure-ca.pem`), the port its bridge listens on
    /// (`proxy_port`, bridged to host vsock 8443) and `proxy.env`, which
    /// every shell sources: the proxy variables and the per-language CA
    /// bundles. Without a proxy, none of them: the guest goes out directly.
    // @port-skip linux-only: SessionDisk.prepareMetadataShare's MITM share, for the Linux proxy (the full function is AppKit-side)
    func writeProxyMeta(_ meta: URL, profile: Profile?, tokenPlan: SessionTokenPlan? = nil,
                        extraNoProxy: [String] = [], registries: [String] = []) throws {
        let fm = FileManager.default
        let names = ["bromure-ca.pem", "proxy_port", "proxy.env", "docker-registries.txt"]
        guard let mitm else {
            for n in names { try? fm.removeItem(at: meta.appendingPathComponent(n)) }
            return
        }
        let port = Self.guestProxyPort
        try mitm.ca.certificatePEM.write(to: meta.appendingPathComponent("bromure-ca.pem"), atomically: true, encoding: .utf8)
        try "\(port)".write(to: meta.appendingPathComponent("proxy_port"), atomically: true, encoding: .utf8)
        // The VMs' subnet and the cluster machines the workspace may reach
        // stay off the proxy (macOS: SessionDisk.extraNoProxy).
        var noProxy = ["localhost", "127.0.0.1", "::1", Self.vmSubnet]
        for x in extraNoProxy where !noProxy.contains(x) { noProxy.append(x) }
        let env: String
        if let profile {
            // A workspace's: macOS's lines (shared), its tokens' fakes, local
            // models and own variables with them. Always cooperative: Linux
            // has no transparent interception to fall back on.
            env = SessionDisk.proxyEnvLines(profile: profile, tokenPlan: tokenPlan, proxyPort: port,
                                            extraNoProxy: Array(noProxy.dropFirst(3)),
                                            extraInsecureRegistries: registries, cooperativeAlways: true)
                .joined(separator: "\n") + "\n"
            // The registries dockerd may talk plain HTTP to (agentd →
            // /etc/docker/daemon.json); written even when empty, so a removal lands.
            try (registries.joined(separator: "\n") + "\n").write(to: meta.appendingPathComponent("docker-registries.txt"),
                                                                 atomically: true, encoding: .utf8)
        } else {
            env = Self.proxyEnv(port: port, noProxy: noProxy)
        }
        try env.write(to: meta.appendingPathComponent("proxy.env"), atomically: true, encoding: .utf8)
    }

    /// agentd's proxy bridge port on a fresh boot (macOS: guestProxyPort):
    /// far from ports people run things on, above the ephemeral range.
    static let guestProxyPort = 65534

    /// The VMs' subnet, kept off the proxy (macOS: SessionDisk.extraNoProxy).
    // @port-skip linux-only: the chosen workspace subnet (DaemonSubnet.swift)
    static var vmSubnet: String { workspaceSubnet.withLockedValue { $0 } }

    /// `proxy.env`: macOS's cooperative-proxy lines and CA hints.
    // @port-skip linux-only: the proxy and CA lines of SessionDisk.prepareMetadataShare's proxy.env
    static func proxyEnv(port: Int, noProxy: [String]) -> String {
        let np = noProxy.joined(separator: ",")
        let ca = "/etc/ssl/certs/ca-certificates.crt"
        return ([
            "# Generated by Bromure AC; do not edit.",
            "export http_proxy=http://127.0.0.1:\(port)",
            "export https_proxy=http://127.0.0.1:\(port)",
            "export HTTP_PROXY=http://127.0.0.1:\(port)",
            "export HTTPS_PROXY=http://127.0.0.1:\(port)",
            "export NO_PROXY=\(np)",
            "export no_proxy=\(np)",
            "export NODE_EXTRA_CA_CERTS=/etc/ssl/certs/bromure-ca.pem",
            "export REQUESTS_CA_BUNDLE=\(ca)",
            "export SSL_CERT_FILE=\(ca)",
            "export CARGO_HTTP_CAINFO=\(ca)",
            "export GIT_SSL_CAINFO=\(ca)",
            "export PIP_CERT=\(ca)",
            "export CURL_CA_BUNDLE=\(ca)",
            "export DENO_CERT=\(ca)",
            "export AWS_CA_BUNDLE=\(ca)",
            "export CLOUDSDK_CORE_CUSTOM_CA_CERTS_FILE=\(ca)",
            "export GRPC_DEFAULT_SSL_ROOTS_FILE_PATH=\(ca)",
            "export SSL_CERT_DIR=/etc/ssl/certs",
        ]).joined(separator: "\n") + "\n"
    }
}
